def load(name):
    return pd.read_csv(RES / name)


def val(d, **kw):
    x = d
    for k, v in kw.items():
        x = x[x[k] == v]
    if len(x) != 1:
        raise KeyError((kw, len(x)))
    return float(x.value.iloc[0])


def vt(d, fmt="{:.3f}", **kw):
    """'val / test' for a cell present in both splits."""
    return " / ".join(fmt.format(val(d, split=s, **kw)) for s in ("val", "test"))


def md_table(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)])


