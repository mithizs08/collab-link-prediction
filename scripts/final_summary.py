"""Phase 7, step 6: results/final_summary.md -- master table, Holm-corrected comparisons, robustness, findings.

  python scripts/final_summary.py

Every number is read from a results (or report) file written by another script; nothing is computed from
scores here. Sources: final_comparison.csv / _tests.csv, two_stage.csv, two_stage_activity_search.csv,
disambiguation_sensitivity.csv, rq2_text_ablation.csv, lgbm_search.csv, ablation.csv, gnn_shortcut_check.csv,
node2vec_alignment_check.csv, report/disambiguation/removal.csv.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from linkpred.eval import report  # noqa: E402

RES = Path("results")
PF, TS, AA = "lightgbm_pair_focused", "two_stage", "adamic_adar"
TAG = "|no_flagged_ids"
COLS = (("hard_active", "macro", "roc_auc", "macro hard_active ROC-AUC (headline)"),
        ("rank_hard_active", "macro", "query_auc", "macro rank_hard_active query AUC (headline)"),
        ("hard", "all", "roc_auc", "pooled hard ROC-AUC (includes activity; affected by newcomer imbalance)"),
        ("random", "all", "roc_auc", "random ROC-AUC"))


class Src:
    def __init__(self):
        self.fc = pd.read_csv(RES / "final_comparison.csv")
        self.ft = pd.read_csv(RES / "final_comparison_tests.csv")
        self.ts = pd.read_csv(RES / "two_stage.csv")
        self.ds = pd.read_csv(RES / "disambiguation_sensitivity.csv")
        self.rq = pd.read_csv(RES / "rq2_text_ablation.csv")

    @staticmethod
    def _pick(d, model, split, p, sub, metric):
        x = d[(d.model == model) & (d.split == split) & (d.protocol == p) & (d.subset == sub) & (d.metric == metric)]
        if len(x) != 1:
            raise KeyError((model, split, p, sub, metric, len(x)))
        return x.iloc[0]

    def row(self, model, split, p, sub, metric):
        for d in (self.fc, self.ts, self.ds, self.rq):
            try:
                return self._pick(d, model, split, p, sub, metric)
            except KeyError:
                continue
        raise KeyError((model, split, p, sub, metric))

    def v(self, *a):
        return float(self.row(*a).value)

    def cell(self, model, split, p, sub, metric):
        try:
            r = self.row(model, split, p, sub, metric)
        except KeyError:
            return "—"
        s = f"{r.value:.3f} [{r.ci_low:.3f}, {r.ci_high:.3f}]"
        try:
            sd = self.row(model, split, p, sub, f"{metric}_seed_sd").value
            s += f" ±{sd:.3f}" if sd > 0 else ""
        except KeyError:
            pass
        return s

    def test(self, name, split, p, sub, metric):
        t = self.ft[(self.ft.model == name) & (self.ft.split == split) & (self.ft.protocol == p) & (self.ft.subset == sub)]
        g = lambda k: t[t.metric == f"{metric}_diff{k}"].iloc[0]
        return g(""), float(g("_p_value").value), float(g("_p_holm").value)


RQS = ("How much do learned models (GNNs, embeddings, feature models) improve over simple graph heuristics for "
       "predicting new collaborations?",
       "Do topical signals (what researchers publish on) add predictive value beyond network structure?",
       "Which features drive predictions, and where do models fail (e.g. newcomers, cross-discipline pairs)?")
HA, RK = ("hard_active", "macro", "roc_auc"), ("rank_hard_active", "macro", "query_auc")
HA_E, HA_N = ("hard_active", "established_matched", "roc_auc"), ("hard_active", "newcomer_matched", "roc_auc")
RK_E, RK_N = ("rank_hard_active", "established_matched", "query_auc"), ("rank_hard_active", "newcomer_matched", "query_auc")
RQ2_SETS = ("structural", "structural+text", "all")
rq2 = lambda lab: f"{PF}[{lab}]"


def main():
    S = Src()
    models = list(dict.fromkeys(S.fc.model))
    best_gnn = next(m for m in models if m.startswith("gnn_"))
    hybrid = next(m for m in models if m.startswith(PF + "+"))
    order = ["prefer_newer", AA, "jaccard", "logreg", "lightgbm", PF, TS, "node2vec", best_gnn, hybrid]
    sc_lab, sc_note = report.shortcut_labels(RES, best_gnn, hybrid)
    label = {"prefer_newer": "prefer_newer (reference: −min prior works, no pair information)",
             PF: f"**{PF} (headline model)**", TS: f"{TS} (P(active) × pair-focused LightGBM; emergent, section 6)", **sc_lab}
    out = ["# Final summary (Phase 7)", "",
           "_Generated by `scripts/final_summary.py`; every number is read from the results files named in each section. "
           "Test split unless stated; validation numbers are in the same files (and `results/final_comparison.md`)._", "",
           "## Research questions (pre-specified)", "",
           "Fixed in the project owner's original plan before any data was seen (recorded in `docs/decisions.md`, "
           "\"Research questions (pre-specified)\"):", ""]
    out += [f"{i}. {q}" for i, q in enumerate(RQS, 1)] + [""]
    out += ["**Protocols.** Headline = macro within-group score: positives and negatives / candidates are compared inside "
            "the established group (no author with ≤ 2 works before the cutoff) and the newcomer group separately, and the "
            "two scores are averaged. `hard_active`: distance-2 positives vs distance-2 non-collaborators who both publish "
            "in the prediction year (ROC-AUC). `rank_hard_active`: each distance-2 positive ranked against up to 100 active "
            "distance-2 candidates (per-query AUC). Pooled `hard` does not match activity, so it rewards predicting who "
            "keeps publishing, and it is affected by newcomer imbalance. `random`: all positives vs random UTS pairs. "
            "Learned models: mean over 5 seeds [seed-mean bootstrap 95% CI] ±seed sd; 5,000 resamples.", "",
            sc_note, ""]

    t = pd.DataFrame({"model": [label.get(m, m) for m in order]})
    for p, sub, metric, title in COLS:
        t[title] = [S.cell(m, "test", p, sub, metric) for m in order]
    out += ["## 1. Master table (test, 2025 predictions)", "",
            "Sources: `results/final_comparison.csv` (all rows except two_stage), `results/two_stage.csv` (two_stage).", "",
            report.to_md(t), ""]

    n_fam = int((S.ft[S.ft.split == "test"].metric.str.endswith("_p_holm")).sum())
    rows = []
    ft = S.ft[S.ft.split == "test"]
    for (name, p, sub), d in ft.groupby(["model", "protocol", "subset"], sort=False):
        for m in d.metric[d.metric.str.endswith("_diff")]:
            dd, pv, ph = S.test(name, "test", p, sub, m[:-5])
            rows.append({"comparison": name, "metric": f"{p} {sub} {m[:-5]}",
                         "difference [95% CI]": f"{dd.value:+.3f} [{dd.ci_low:+.3f}, {dd.ci_high:+.3f}]",
                         "raw p": f"{pv:.4f}", "Holm p": f"{ph:.4f}", "significant (Holm < 0.05)": "yes" if ph < 0.05 else "no"})
    out += [f"## 2. Primary comparisons (test; one paired bootstrap on seed-averaged scores, Holm across the {n_fam}-test "
            "family)", "",
            "Family defined in `docs/decisions.md` (\"Phase 7 design\", extended in \"RQ2 design\") before the "
            "corresponding test runs. Source: `results/final_comparison_tests.csv`. Smallest attainable raw p = 0.0002 "
            "(5,000 resamples).", "", report.to_md(pd.DataFrame(rows)), ""]

    out += rq2_section(S)
    out += robustness(S)
    out += findings(S, best_gnn, hybrid)
    out += emergent(S, best_gnn)
    (RES / "final_summary.md").write_text("\n".join(out))
    print("wrote results/final_summary.md")


def rq2_section(S: Src) -> list[str]:
    out = ["## 3. RQ2: text ablation of the pair-focused LightGBM (`results/rq2_text_ablation.csv`, `_tests.csv`)", "",
           "Same model, parameters, mix and seeds (not re-tuned per feature set); structural = 14 features, "
           "structural+text = 18, all = 27 (+ temporal). Validation first, then test (`docs/decisions.md`, \"RQ2 design\").", ""]
    cells = ((HA, "hard_active macro"), (HA_E, "hard_active established"), (HA_N, "hard_active newcomer"),
             (RK, "rank_hard_active macro"), (RK_E, "rank_hard_active established"), (RK_N, "rank_hard_active newcomer"))
    for split in ("test", "val"):
        t = pd.DataFrame({"feature set": list(RQ2_SETS)})
        for c, title in cells:
            t[title] = [S.cell(rq2(lab), split, *c) for lab in RQ2_SETS]
        out += [f"**{split}** (hard_active: ROC-AUC; rank_hard_active: query AUC)", "", report.to_md(t), ""]
    rows = []
    for a, b, cs in (("structural+text", "structural", (HA, RK, HA_E, HA_N, RK_E, RK_N)), ("all", "structural+text", (HA, RK))):
        for c in cs:
            d, pv, ph = S.test(f"{rq2(a)} - {rq2(b)}", "test", *c)
            rows.append({"comparison": f"{a} − {b}", "metric": " ".join(c),
                         "difference [95% CI]": f"{d.value:+.3f} [{d.ci_low:+.3f}, {d.ci_high:+.3f}]",
                         "raw p": f"{pv:.4f}", "Holm p (32-test family)": f"{ph:.4f}"})
    out += ["**Paired tests (test)**", "", report.to_md(pd.DataFrame(rows)), ""]
    return out


def robustness(S: Src) -> list[str]:
    out = ["## 4. Robustness", ""]
    s = pd.read_csv(RES / "lgbm_search.csv")
    s = s[(s.metric == "roc_auc") & s.model.str.startswith(PF + "|")].sort_values("value", ascending=False)
    top = s.head(5)[["model", "value"]].assign(value=lambda d: d.value.round(4))
    old = s[s.model == f"{PF}|leaves=3|lr=0.03|min_child=300"].value.iloc[0]
    big = s[s.model.str.contains("min_child=500|min_child=1000", regex=True)].value
    out += ["### 4.1 Grid edge for the pair-focused LightGBM (validation only; `results/lgbm_search.csv`)", "",
            f"Extended grid: 50 configs (2 leaves and min_child 500 / 1,000 added). Selected: `{s.model.iloc[0]}` "
            f"(validation pooled hard_active ROC-AUC {s.value.iloc[0]:.4f}), replacing `leaves=3|lr=0.03|min_child=300` "
            f"({old:.4f}). Larger min_child is worse everywhere ({big.min():.4f}–{big.max():.4f}). The surface is flat: "
            "the change is rule-driven, not evidence of a better model. All 5 seeds and every downstream model were "
            "retrained with the new parameters.", "", report.to_md(top), ""]
    rm = pd.read_csv(Path("report/disambiguation/removal.csv")).set_index("split")
    t = pd.DataFrame({"model": ["prefer_newer", AA, PF]})
    for p, sub, metric, title in COLS[:2]:
        t[f"{title.split(' (')[0]}, main"] = [S.cell(m, "test", p, sub, metric) for m in t.model]
        t[f"{title.split(' (')[0]}, flagged IDs removed"] = [S.cell(m + TAG, "test", p, sub, metric) for m in t.model]
    r = rm.loc["test"]
    out += ["### 4.2 Disambiguation sensitivity (test; `results/disambiguation_sensitivity.csv`, "
            "`report/disambiguation/removal.csv`)", "",
            f"All {int(r.flagged_nodes):,} flagged author IDs present in the test input graph "
            f"({int(r.flagged_uts_nodes):,} UTS) removed from the graph and every pair set, same splits and seeds; "
            f"input edges {int(r.edges_before):,} → {int(r.edges_after):,}; positives {int(r.positives_before):,} → "
            f"{int(r.positives_after):,}; activity-matched negatives {int(r.neg_hard_active_before):,} → "
            f"{int(r.neg_hard_active_after):,}. **The flag is a heuristic** (same normalised name, more than one ID at "
            "the same institution): it removes true split profiles but also correctly identified authors who share a "
            "name, and it cannot find merged profiles.", "", report.to_md(t), ""]
    al = pd.read_csv(RES / "node2vec_alignment_check.csv").set_index("model").value
    out += ["### 4.3 node2vec alignment (`results/node2vec_alignment_check.csv`, validation)", "",
            f"Hadamard classifier transferred {al['node2vec_alignment|op=hadamard|transferred']:.3f} vs fitted within "
            f"validation {al['node2vec_alignment|op=hadamard|within_val']:.3f}; the selected L1 operator "
            f"{al['node2vec_alignment|op=l1|transferred']:.3f}. node2vec's weakness is the operator / embedding, not the "
            "alignment.", ""]
    return out


def _tst(S, name, c):
    d, _, ph = S.test(name, "test", *c)
    return f"{d.value:+.3f} [{d.ci_low:+.3f}, {d.ci_high:+.3f}], Holm p = {ph:.4f}"


def findings(S: Src, best_gnn: str, hybrid: str) -> list[str]:
    """Findings mapped to the pre-specified research questions; every number is read from a results file."""
    v = lambda m, c: S.v(m, "test", *c)
    tst = lambda name, c: _tst(S, name, c)
    rm = pd.read_csv(Path("report/disambiguation/removal.csv")).set_index("split").loc["test"]
    imp = pd.read_csv(Path("report/features/importance.csv"))
    imp = imp[imp.model == PF]
    fam = imp.groupby("family").gain.sum() / imp.gain.sum()
    top = imp.groupby("feature").gain.mean().sort_values(ascending=False)
    top = (top / top.sum()).head(3)
    st, stx, al_ = rq2("structural"), rq2("structural+text"), rq2("all")
    out = ["## 5. Findings by research question", "",
           f"### RQ1. {RQS[0]}", ""]
    out.append(
        f"1. **Feature models improve on heuristics, modestly; representation learning does not.** The pair-focused "
        f"LightGBM is the best model: macro hard_active {v(PF, HA):.3f} and macro rank_hard_active {v(PF, RK):.3f}, vs "
        f"Adamic-Adar {v(AA, HA):.3f} / {v(AA, RK):.3f} ({tst(f'{PF} - {AA}', HA)}; {tst(f'{PF} - {AA}', RK)}). "
        f"General feature models gain much less: logistic regression {v('logreg', HA):.3f}, general LightGBM "
        f"{v('lightgbm', HA):.3f} (LightGBM − AA {tst(f'lightgbm - {AA}', HA)}). An AUC of about 0.80 means about one in "
        "five positive–negative comparisons is ranked the wrong way round: useful for ranking candidates, not for "
        "predicting individual collaborations.")
    out.append(
        f"2. **Embeddings and GNNs lost to Adamic-Adar.** node2vec {v('node2vec', HA):.3f} and the best GNN "
        f"{v(best_gnn, HA):.3f} on macro hard_active (node2vec − AA {tst(f'node2vec - {AA}', HA)}; GNN − AA "
        f"{tst(f'{best_gnn} - {AA}', HA)}). The GNN was trained with the distance shortcut (section 6), so its ceiling is "
        f"unknown without retraining. Its out-of-fold score added to the pair-focused LightGBM (hybrid, secondary) "
        f"changes macro hard_active by {tst(f'{hybrid} - {PF}', HA)}: under a hundredth of AUC, from a shortcut-trained model.")
    out.append(
        f"3. **The RQ1 answer survives the robustness checks, which are limited.** With the flagged possible-duplicate "
        f"author IDs removed, the pair-focused LightGBM still beats Adamic-Adar ({v(PF + TAG, HA):.3f} vs "
        f"{v(AA + TAG, HA):.3f}, {tst(f'{PF}{TAG} - {AA}{TAG}', HA)}), but the heuristic flag removes "
        f"{1 - rm.d2_positives_after / rm.d2_positives_before:.0%} of the test distance-2 positives (section 4.2). "
        f"Extending the hyperparameter grid left test macro hard_active at {v(PF, HA):.3f} (section 4.1).")
    out += ["", f"### RQ2. {RQS[1]}", ""]
    out.append(
        f"4. **Yes, a small, consistent amount.** Adding the 4 text features to the 14 structural ones raises the "
        f"pair-focused LightGBM from {v(st, HA):.3f} to {v(stx, HA):.3f} macro hard_active ({tst(f'{stx} - {st}', HA)}) and "
        f"from {v(st, RK):.3f} to {v(stx, RK):.3f} macro rank_hard_active ({tst(f'{stx} - {st}', RK)}); validation shows the "
        "same direction (section 3). The gain is present in both groups on the ranking task (established "
        f"{tst(f'{stx} - {st}', RK_E)}; newcomer {tst(f'{stx} - {st}', RK_N)}) and for established pairs on hard_active "
        f"({tst(f'{stx} - {st}', HA_E)}); for newcomer pairs on hard_active it is "
        f"{tst(f'{stx} - {st}', HA_N)}, not significant after correction (validation: not significant either).")
    out.append(
        f"5. **Text is worth about as much as the temporal block, and neither replaces structure.** Adding the 9 temporal "
        f"features on top of structural+text adds a further {tst(f'{al_} - {stx}', HA)} (hard_active). Even with all 27 "
        f"features the model is at {v(al_, HA):.3f}, and structure alone already gets {v(st, HA):.3f}: what researchers publish "
        "on helps, but most of what the model can separate among friend-of-friend pairs is structural. (The temporal "
        "increment is measured on top of text; the order of adding blocks is fixed by the design, not tested both ways.)")
    out += ["", f"### RQ3. {RQS[2]} — preliminary; completed in Phase 8", ""]
    out.append(
        f"6. **Drivers (preliminary; gain importance, `report/features/importance.csv`).** For the pair-focused LightGBM "
        f"the gain splits {fam['temporal']:.0%} temporal, {fam['text']:.0%} text, {fam['structural']:.0%} structural; the top "
        f"features are " + ", ".join(f"`{f}` ({x:.0%})" for f, x in top.items()) + ". Caveats: gain is not causal, "
        "correlated features share credit, and `rw_aa` / `rw_cn` (classed temporal) are recency-weighted Adamic-Adar "
        "and common-neighbour counts, i.e. structure weighted by how recent the shared ties are.")
    out.append(
        f"7. **Failures (preliminary).** Newcomer pairs are harder than established ones for the headline model "
        f"(hard_active {v(PF, HA_N):.3f} vs {v(PF, HA_E):.3f}; rank_hard_active {v(PF, RK_N):.3f} vs {v(PF, RK_E):.3f}). "
        f"The model is a specialist: on random pairs it scores {v(PF, ('random', 'all', 'roc_auc')):.3f} vs "
        f"{v('lightgbm', ('random', 'all', 'roc_auc')):.3f} for the general LightGBM, so it should only rank friend-of-friend "
        "candidates. Cross-discipline pairs have not been analysed yet; that, per-feature attributions and an error "
        "analysis are Phase 8.")
    return out + [""]


def emergent(S: Src, best_gnn: str) -> list[str]:
    """Findings that answer none of the pre-specified questions, found along the way."""
    v = lambda m, c: S.v(m, "test", *c)
    tst = lambda name, c: _tst(S, name, c)
    H_ALL, H_MAC = ("hard", "all", "roc_auc"), ("hard", "macro", "roc_auc")
    ab = pd.read_csv(RES / "ablation.csv")
    ab = ab[(ab.split == "test") & (ab.subset == "macro") & (ab.metric == "roc_auc")].groupby(["model", "protocol"]).value.mean()
    sc = pd.read_csv(RES / "gnn_shortcut_check.csv")
    sc = sc[(sc.subset == "far_negatives_vs_distance2_positives")].groupby("model").value.mean()
    pooled = lambda m: S.v(m, "test", "hard_active", "all", "roc_auc")
    a = pd.read_csv(RES / "two_stage_activity_search.csv")
    a = a[a.metric == "roc_auc"].sort_values("value", ascending=False).iloc[0]
    act = S.ts[(S.ts.model == "activity_lightgbm") & (S.ts.metric == "roc_auc") & (S.ts.split == "test")].value.mean()
    out = ["## 6. Emergent findings (not pre-specified)", "",
           "These shaped the evaluation design but answer none of the three research questions.", ""]
    out.append(
        f"- **Activity confound.** Protocols whose negatives are not activity-matched mostly measure who keeps publishing. "
        f"The general LightGBM scores {v('lightgbm', H_ALL):.3f} on pooled hard but {v('lightgbm', HA):.3f} on macro "
        f"hard_active; in its ablation (`results/ablation.csv`) temporal features alone reach "
        f"{ab[('lightgbm[temporal]', 'hard')]:.3f} macro hard but {ab[('lightgbm[temporal]', 'hard_active')]:.3f} macro "
        "hard_active. This is why `hard_active` is the headline.")
    out.append(
        f"- **Newcomer imbalance.** Activity matching makes newcomers rare among negatives, so pooled numbers reward "
        f"newcomer status. The prefer_newer reference (no pair information) scores {pooled('prefer_newer'):.3f} on pooled "
        f"hard_active but {v('prefer_newer', HA):.3f} macro; the headline therefore compares within groups.")
    out.append(
        f"- **Distance shortcut.** Training on distance-2 negatives with positives at any distance lets distance alone "
        f"separate the classes (`results/gnn_shortcut_check.csv`: ROC-AUC of far random negatives vs distance-2 positives, "
        f"> 0.5 = shortcut): pre-fix pair-focused LightGBM {sc[PF + '_shortcut']:.3f}, retrained {sc[PF]:.3f}, best GNN "
        f"{sc[best_gnn]:.3f}. The LightGBM was retrained; the Colab GNNs were not, which is the caveat on every GNN and "
        "hybrid row.")
    t = pd.DataFrame({"model": [TS, "lightgbm", PF]})
    for c, title in ((H_ALL, "pooled hard ROC-AUC (includes activity)"), (H_MAC, "macro hard ROC-AUC (includes activity)"),
                     (HA, "macro hard_active ROC-AUC"), (RK, "macro rank_hard_active query AUC")):
        t[title] = [S.cell(m, "test", *c) for m in t.model]
    out.append(
        f"- **Two-stage model does not help.** P(both active) × pair-focused LightGBM scores {v(TS, H_ALL):.3f} on pooled "
        f"hard vs {v('lightgbm', H_ALL):.3f} for the general LightGBM ({tst(f'{TS} - lightgbm', H_ALL)}; macro hard "
        f"{tst(f'{TS} - lightgbm', H_MAC)}), although its stage-1 activity model (`{a.model}`, validation activity ROC-AUC "
        f"{a.value:.3f}, test {act:.3f}) is good at its own task. The general model already learns activity jointly with "
        "the pair signal; the product of two separately trained probabilities loses that. Validation showed the same "
        "before test was run (`results/two_stage.csv`).")
    out += ["", report.to_md(t), ""]
    return out


if __name__ == "__main__":
    main()
