"""Summaries of the built splits: report/splits/*.csv and the generated block of docs/splits.md."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from linkpred.data.audit import _md_table, write_markdown

SUMMARY_COLS = [
    "split", "cutoff", "window_end", "nodes", "nodes_with_edges", "edges", "uts_nodes",
    "uts_nodes_with_edges", "positives", "neg_random", "neg_hard", "hard_candidate_pool",
    "ranking_k", "ranking_rows",
]
EXCLUSION_COLS = [
    "split", "window_uts_pairs_with_edge", "excluded_connected_in_graph",
    "excluded_prior_hyper_work_only", "positives",
]
RANK_HARD_COLS = [
    "split", "rank_hard_queries", "rank_hard_full", "rank_hard_partial", "rank_hard_no_candidates",
    "rank_hard_median_candidates", "rank_hard_rows",
]
ACTIVE_COLS = [
    "split", "active_uts_nodes", "hard_active_pool", "neg_hard_active", "rank_hard_active_queries",
    "rank_hard_active_full", "rank_hard_active_partial", "rank_hard_active_no_candidates",
    "rank_hard_active_median_candidates", "rank_hard_active_rows",
]
COLD_COLS = [
    "split", "positives", "pos_cold_start_any", "pos_cold_start_both", "pos_with_isolated_endpoint",
]


def tables(stats: dict[str, dict]) -> dict[str, pd.DataFrame]:
    rows = [{"split": k, **v} for k, v in stats.items()]
    df = pd.DataFrame(rows)
    dist = pd.DataFrame([{"split": k, "positives": v["positives"], **v["distance"]} for k, v in stats.items()])
    dist_neg = pd.DataFrame([{"split": k, "pairs": v["neg_random"], **v["distance_neg_random"]}
                             for k, v in stats.items()])
    cold = df[COLD_COLS].copy()
    cold["share_cold_start_any"] = cold["pos_cold_start_any"] / cold["positives"]
    return {
        "summary": df[SUMMARY_COLS],
        "exclusions": df[EXCLUSION_COLS],
        "distance": dist[["split", "positives", "d2", "d3", "d4plus", "disconnected",
                          "share_d2", "share_d3", "share_d4plus", "share_disconnected", "d1_or_less"]],
        "cold_start": cold,
        "rank_hard": df[RANK_HARD_COLS],
        "activity_matched": df[ACTIVE_COLS],
        "distance_neg_random": dist_neg[["split", "pairs", "d2", "d3", "d4plus", "disconnected",
                                         "share_d2", "share_d3", "share_d4plus", "share_disconnected"]],
    }


def render(t: dict[str, pd.DataFrame], cold_max: int) -> str:
    return "\n".join([
        "<!-- BEGIN GENERATED -->",
        "_Generated by `linkpred.data.splits_report` from `report/splits/`; do not edit by hand._",
        "",
        "## Per-split counts",
        "`nodes` = all authors with a work before the cutoff (isolated authors included); "
        "`nodes_with_edges` = those with at least one co-author. Negatives are 1:1 per type. "
        "`hard_candidate_pool` = all eligible distance-2 UTS–UTS pairs the hard negatives are drawn from.",
        "",
        _md_table(t["summary"]),
        "",
        "## How positives were selected",
        "`window_uts_pairs_with_edge` = UTS–UTS pairs (both in the graph) with a ≤25-author joint work in "
        "the window. Removed: pairs already connected in the input graph, and pairs whose only earlier "
        "joint work was hyper-authored (their first co-authorship is not in the window).",
        "",
        _md_table(t["exclusions"]),
        "",
        "## Shortest-path distance of positives in the input graph",
        "Unweighted distance in the full input graph (all authors). Distance 1 is impossible by "
        "construction (`d1_or_less` must be 0).",
        "",
        _md_table(t["distance"]),
        "",
        "For comparison, the same distribution for the random negatives "
        "(hard negatives are all at distance 2 by construction):",
        "",
        _md_table(t["distance_neg_random"]),
        "",
        "## Hard ranking candidates (rank_hard protocol)",
        "One query per distance-2 positive; up to 100 candidates at distance 2 from the head. "
        "`rank_hard_full` queries have all 100; `partial` have fewer (all that exist) and are "
        "reported as a separate stratum.",
        "",
        _md_table(t["rank_hard"]),
        "",
        "## Activity-matched sets (hard_active / rank_hard_active protocols)",
        "Active = at least one work in the prediction window. This window information selects evaluation "
        "pairs only (and training labels on the train split); it is never a model input. `neg_hard_active` "
        "is 1:1 against distance-2 positives, drawn from `hard_active_pool`.",
        "",
        _md_table(t["activity_matched"]),
        "",
        f"## Cold-start positives (an endpoint with ≤ {cold_max} works before the cutoff)",
        _md_table(t["cold_start"]),
        "<!-- END GENERATED -->",
    ])


def write(cfg: dict, stats: dict[str, dict]) -> dict[str, pd.DataFrame]:
    out = Path(cfg["paths"]["report"]) / "splits"
    out.mkdir(parents=True, exist_ok=True)
    t = tables(stats)
    for name, df in t.items():
        df.to_csv(out / f"{name}.csv", index=False)
    write_markdown(Path("docs/splits.md"), render(t, cfg["splits"]["cold_start_max_works"]), title="Temporal splits")
    return t
