FINAL = ["logreg", "lightgbm", "lightgbm_d2_specialist", "lightgbm_pair_focused"]
PAIR_PROTOCOLS = ("hard_active", "rank_hard_active", "hard", "rank_hard")
ABL_ORDER = ["structural", "temporal", "text", "structural+temporal", "structural+text", "all"]


def seed_summary(df: pd.DataFrame) -> pd.DataFrame:
    """mean ± sd of point estimates over seeds, plus the mean CI bounds."""
    g = df.groupby(["model", "split", "protocol", "subset", "metric"])
    return g.agg(mean=("value", "mean"), sd=("value", "std"), n_seeds=("seed", "nunique"),
                 ci_low=("ci_low", "mean"), ci_high=("ci_high", "mean")).reset_index()


def msd(x) -> str:
    return f"{x['mean']:.3f} ± {0 if pd.isna(x['sd']) else x['sd']:.3f}"


def table(s: pd.DataFrame, split, protocol, subset, metrics, models) -> pd.DataFrame:
    d = s[(s.split == split) & (s.protocol == protocol) & (s.subset == subset)]
    out = pd.DataFrame({"model": models})
    for m in metrics:
        x = d[d.metric == m].set_index("model")
        out[m] = [msd(x.loc[k]) if k in x.index else "" for k in models]
    return out


def heuristic_rows(base: pd.DataFrame, split, protocol, subset, metrics, models) -> pd.DataFrame:
    t = report.metric_table(base, protocol, subset, split, metrics, models)
    t["model"] = t["model"] + " (heuristic)"
    return t


def write_feature_report(cfg: dict, mix: dict, params: dict, val_best: dict, pf_params: dict | None = None) -> None:
    res, figs = Path(cfg["paths"]["results"]), Path(cfg["paths"]["figures"])
    fm = pd.read_csv(res / "feature_models.csv")
    base = pd.read_csv(res / "baselines.csv")
    paired = pd.read_csv(res / "feature_models_paired.csv")
    grid = pd.read_csv(res / "negative_mix_grid.csv")
    search = pd.read_csv(res / "lgbm_search.csv")
    abl = pd.read_csv(res / "ablation.csv")
    hl = pd.read_csv(res / "half_life_selection.csv")
    cov = pd.read_csv(Path(cfg["paths"]["report"]) / "features" / "coverage.csv")
    imp = pd.read_csv(Path(cfg["paths"]["report"]) / "features" / "importance.csv")
    s = seed_summary(fm)
    sa = seed_summary(abl)
    ks_h = [f"hits@{k}" for k in cfg["evaluation"]["rank_ks_hard"]]
    ks_r = [f"hits@{k}" for k in cfg["evaluation"]["rank_ks_random"]]

    out = ["# Feature-based models (logistic regression, LightGBM)", "",
           "_Generated by `scripts/run_feature_models.py` from `results/feature_models.csv`, "
           "`feature_models_paired.csv`, `negative_mix_grid.csv`, `lgbm_search.csv`, `ablation.csv`, "
           "`half_life_selection.csv`. Learned models: mean ± sd of the point estimate over 5 seeds "
           "(logistic regression is deterministic, so its sd is 0). Heuristic rows: point estimate "
           "[bootstrap 95% CI] from `results/baselines.csv`._", "",
           "**How to read this.** `hard_active` (distance-2 positives vs hard negatives whose two authors both "
           "publish in the prediction year) is the lead pair-level metric: it asks *which pairs collaborate* "
           "among people who are all still publishing. `hard` keeps negatives with inactive authors and therefore "
           "*includes activity*: a model can score well on it by predicting who keeps publishing (Phase 4 finding, "
           "docs/decisions.md). Activity is used only to select evaluation pairs, never as a model input.", ""]

    out += ["## Choices made on validation", "",
            f"- Negative mix: logistic regression **hard fraction {mix['logreg'][0]:g}, 1:{mix['logreg'][1]}**; "
            f"LightGBM **hard fraction {mix['lightgbm'][0]:g}, 1:{mix['lightgbm'][1]}** (rule: best val `hard` ROC-AUC "
            "among mixes with val rank_random MRR ≥ 90% of the best mix).",
            f"- LightGBM: num_leaves {params['num_leaves']}, learning_rate {params['learning_rate']:g}, "
            f"min_child_samples {params['min_child_samples']}, subsample {params['subsample']}, "
            f"colsample_bytree {params['colsample_bytree']}; early stopping on val hard AP.",
            *([f"- Pair-focused LightGBM: training negatives = activity-matched hard negatives from the 2023 window "
               f"(1:{mix['lightgbm'][1]}); num_leaves {pf_params['num_leaves']}, learning_rate {pf_params['learning_rate']:g}, "
               f"min_child_samples {pf_params['min_child_samples']}; early stopping on val hard_active AP, "
               "selected by val hard_active ROC-AUC."] if pf_params else []),
            f"- Recency half-life: {hl.sort_values('value', ascending=False)['model'].iloc[0].split('=')[1]} years "
            "(val hard ROC-AUC of recency-weighted Adamic-Adar alone).",
            "- Validation-best heuristic per protocol (paired-test reference): "
            + ", ".join(f"{p}: {h}" for p, h in val_best.items()) + "; Adamic-Adar is also tested on the four pair-level protocols.",
            ""]

    out += ["## Embedding coverage (authors with ≥ 1 embedded work before the cutoff)", "",
            report.to_md(cov.assign(**{c: cov[c].map(lambda v: f"{v:.3f}") for c in cov.columns if c.startswith("share")})), ""]

    # Grid
    out += ["## Negative-mix grid (validation, seed 0, default LightGBM params)", ""]
    rows = []
    for m, d in grid.groupby("model", sort=False):
        get = lambda p, mt=None, sub=None: d[(d.protocol == p) & (d.subset == (sub or report.HEADLINE[p][0]))
                                            & (d.metric == (mt or report.HEADLINE[p][1]))]["value"].iloc[0]
        rows.append({"model | mix": m, "hard_active ROC-AUC": f"{get('hard_active'):.4f}",
                     "hard ROC-AUC": f"{get('hard'):.4f}", "hard AP": f"{get('hard', 'average_precision'):.4f}",
                     "rank_hard MRR": f"{get('rank_hard'):.4f}", "rank_random MRR": f"{get('rank_random'):.4f}",
                     "random ROC-AUC": f"{get('random'):.4f}"})
    out += [report.to_md(pd.DataFrame(rows)), ""]

    out += ["## LightGBM search (validation, chosen mix, seed 0)", ""]
    sp_ = search.pivot_table(index="model", columns="metric", values="value").reset_index()
    sp_ = sp_[["model", "roc_auc", "average_precision", "n_trees"]].sort_values("roc_auc", ascending=False)
    out += [report.to_md(sp_.round(4)), ""]

    for split in ("test", "val"):
        out += [f"## Final models — {split}", ""]
        sections = [("hard_active", "all", ["roc_auc", "average_precision"]),
                    ("rank_hard_active", "full_candidates", ks_h + ["mrr", "query_auc"]),
                    ("rank_hard_active", "all", ["query_auc"]),
                    ("hard", "all", ["roc_auc", "average_precision"]),
                    ("rank_hard", "full_candidates", ks_h + ["mrr", "query_auc"]),
                    ("rank_hard", "all", ["query_auc"]),
                    ("rank_random", "all", ks_r + ["mrr"]),
                    ("random", "all", ["roc_auc", "average_precision"])]
        for p, sub, metrics in sections:
            refs = sorted({val_best.get(p, "adamic_adar"), "adamic_adar"} if p in PAIR_PROTOCOLS else {val_best[p]})
            t = pd.concat([table(s, split, p, sub, metrics, FINAL), heuristic_rows(base, split, p, sub, metrics, refs)])
            tag = {"hard_active": " (lead pair-level metric)", "hard": " (includes activity)"}.get(p, "")
            out += [f"### {p} — {sub}{tag}", "", report.to_md(t), ""]
        out += [f"### Cold start vs established ({split})", ""]
        cs = []
        for p, metric in (("hard_active", "roc_auc"), ("rank_hard_active", "query_auc"),
                          ("hard", "roc_auc"), ("rank_hard", "query_auc")):
            for sub in ("cold_start", "established"):
                d = s[(s.split == split) & (s.protocol == p) & (s.subset == sub) & (s.metric == metric)].set_index("model")
                b = base[(base.split == split) & (base.protocol == p) & (base.subset == sub) & (base.metric == metric)].set_index("model")
                row = {"protocol / subset": f"{p} {metric} — {sub}"}
                row.update({m: msd(d.loc[m]) for m in FINAL if m in d.index})
                if "adamic_adar" in b.index:
                    row["adamic_adar"] = f"{b.loc['adamic_adar', 'value']:.3f}"
                cs.append(row)
        out += [report.to_md(pd.DataFrame(cs)), ""]

    out += ["## Paired bootstrap tests (test, per seed)", "",
            "Difference = model − reference on identical test pairs/queries. `sig. seeds` = seeds with p < 0.05 "
            "and the difference in the stated direction.", ""]
    pv = paired[paired.metric.str.endswith("_p_value")].rename(columns={"value": "p"})
    dv = paired[~paired.metric.str.endswith("_p_value")]
    m = dv.merge(pv[["model", "protocol", "seed", "p"]], on=["model", "protocol", "seed"])
    rows = []
    for (model, p), d in m.groupby(["model", "protocol"], sort=False):
        rows.append({"comparison": model, "protocol": p, "metric": d["metric"].iloc[0],
                     "mean diff": f"{d['value'].mean():+.4f}",
                     "diff range (seeds)": f"[{d['value'].min():+.4f}, {d['value'].max():+.4f}]",
                     "sig. seeds (better)": f"{int(((d.p < 0.05) & (d.value > 0)).sum())}/{len(d)}",
                     "sig. seeds (worse)": f"{int(((d.p < 0.05) & (d.value < 0)).sum())}/{len(d)}",
                     "median p": f"{d['p'].median():.3f}"})
    out += [report.to_md(pd.DataFrame(rows)), ""]

    out += ["## Ablation by feature family (general LightGBM, chosen mix and params, test)", ""]
    ab = []
    for lab in ABL_ORDER:
        mname = f"lightgbm[{lab}]"
        row = {"features": lab}
        for p, sub, metric in (("hard_active", "all", "roc_auc"), ("hard_active", "cold_start", "roc_auc"),
                               ("hard_active", "established", "roc_auc"), ("rank_hard_active", "full_candidates", "mrr"),
                               ("hard", "all", "roc_auc"), ("rank_hard", "full_candidates", "mrr")):
            d = sa[(sa.model == mname) & (sa.split == "test") & (sa.protocol == p) & (sa.subset == sub) & (sa.metric == metric)]
            row[f"{p} {metric} {sub}"] = msd(d.iloc[0]) if len(d) else ""
        ab.append(row)
    out += [report.to_md(pd.DataFrame(ab)), "", "![ablation](../figures/feature_models_ablation_test.png)", ""]

    out += ["## LightGBM gain importance by family (mean over seeds, final model)", ""]
    fi = imp[imp.model == "lightgbm"].groupby(["seed", "family"])["gain"].sum().groupby("family").mean()
    fi = (fi / fi.sum()).sort_values(ascending=False)
    out += [report.to_md(pd.DataFrame({"family": fi.index, "share of total gain": [f"{v:.3f}" for v in fi.values]})), ""]
    top = imp[imp.model == "lightgbm"].groupby("feature")["gain"].mean().sort_values(ascending=False).head(10)
    out += [report.to_md(pd.DataFrame({"feature": top.index, "mean gain": [f"{v:.1f}" for v in top.values]})), ""]

    act_path = res / "activity_diagnostic.csv"
    if act_path.exists():
        act = pd.read_csv(act_path)
        actp = pd.read_csv(res / "activity_diagnostic_paired.csv")
        out += ["## Diagnostic: how much of the hard gain is author activity?", "",
                "Every positive needs both authors to publish in the prediction year; most hard negatives do not "
                "(an author has left UTS or stopped publishing). `neg_both_active` keeps only hard negatives whose "
                "two authors both have a work in the prediction year. This uses label-window information to choose "
                "the evaluation subset only (no model sees it): it is an analysis, not a deployable setting. "
                "Generated from `results/activity_diagnostic.csv` and `activity_diagnostic_paired.csv`.", ""]
        for split in ("test", "val"):
            a = act[(act.split == split)]
            nn = a[(a.metric == "n_negatives") & (a.model == "adamic_adar")].set_index("subset")["value"]
            rows = []
            for mname, d in a[a.metric == "roc_auc"].groupby("model", sort=False):
                row = {"model": mname}
                for sub in ("all", "neg_both_active"):
                    x = d[d.subset == sub]["value"]
                    row[f"hard ROC-AUC, {sub} (n_neg={int(nn[sub]):,})"] = (
                        f"{x.mean():.3f} ± {x.std():.3f}" if len(x) > 1 else f"{x.mean():.3f}")
                pp = actp[(actp.split == split) & (actp.model == f"{mname} - adamic_adar")]
                for sub in ("all", "neg_both_active"):
                    dd = pp[(pp.subset == sub) & (pp.metric == "roc_auc_diff")]
                    pv = pp[(pp.subset == sub) & (pp.metric == "roc_auc_diff_p_value")].set_index("seed")["value"]
                    if len(dd):
                        sig = int(sum((pv.loc[s_] < 0.05) and (v > 0) for s_, v in zip(dd.seed, dd.value)))
                        worse = int(sum((pv.loc[s_] < 0.05) and (v < 0) for s_, v in zip(dd.seed, dd.value)))
                        row[f"vs AA, {sub}"] = f"{dd.value.mean():+.3f} (better {sig}/5, worse {worse}/5)"
                rows.append(row)
            out += [f"### {split}", "", report.to_md(pd.DataFrame(rows).fillna("—")), ""]

    out += ["## Appendix: diagnostic_all_vs_hard", "", report.DIAGNOSTIC_WARNING, "",
            report.to_md(table(s, "test", "diagnostic_all_vs_hard", "all", ["roc_auc", "average_precision"], FINAL)), ""]
    out += ["## Figures", "", "![models](../figures/feature_models_protocols_test.png)", ""]
    (res / "feature_models.md").write_text("\n".join(out))

    ablation_figure(sa, base, figs / "feature_models_ablation_test.png")
    comparison_figure(s, base, figs / "feature_models_protocols_test.png")


def _style(ax, title, xlabel):
    report._style(ax, title, xlabel)


def ablation_figure(sa: pd.DataFrame, base: pd.DataFrame, path: Path) -> None:
    panels = [("hard_active", "all", "roc_auc", "hard_active ROC-AUC (lead)\nall distance-2 positives"),
              ("hard_active", "cold_start", "roc_auc", "hard_active ROC-AUC\ncold-start positives"),
              ("hard_active", "established", "roc_auc", "hard_active ROC-AUC\nestablished positives"),
              ("rank_hard_active", "full_candidates", "mrr", "rank_hard_active MRR\nfull-candidate queries"),
              ("hard", "all", "roc_auc", "hard ROC-AUC (includes activity)\nall distance-2 positives"),
              ("rank_hard", "full_candidates", "mrr", "rank_hard MRR (includes activity)\nfull-candidate queries")]
    fig, axes = plt.subplots(2, 3, figsize=(12, 6.6), dpi=150)
    fig.patch.set_facecolor(SURFACE)
    y = np.arange(len(ABL_ORDER))[::-1]
    for ax, (p, sub, metric, title) in zip(axes.ravel(), panels):
        d = sa[(sa.split == "test") & (sa.protocol == p) & (sa.subset == sub) & (sa.metric == metric)]
        d = d.set_index("model").reindex([f"lightgbm[{a}]" for a in ABL_ORDER])
        ax.barh(y, d["mean"], color=SERIES[0], height=0.6)
        ax.errorbar(d["mean"], y, xerr=d["sd"].fillna(0), fmt="none", ecolor=INK, elinewidth=1, capsize=2)
        hi = float((d["mean"] + d["sd"].fillna(0)).max())
        b = base[(base.split == "test") & (base.protocol == p) & (base.subset == sub) & (base.metric == metric)
                 & (base.model == "adamic_adar")]
        ref = float(b["value"].iloc[0]) if len(b) else None
        lo = 0.5 if metric != "mrr" else 0.0
        top = max(hi, ref or 0) * 1.08
        for yi, v, sd in zip(y, d["mean"], d["sd"].fillna(0)):
            ax.text(v + sd + 0.01 * (top - lo), yi, f"{v:.3f}", va="center", fontsize=7.5, color=INK_2)
        if ref is not None:
            ax.axvline(ref, color=SERIES[1], linewidth=1.5, linestyle=(0, (3, 2)))
        ax.set_yticks(y)
        ax.set_yticklabels(ABL_ORDER)
        ax.set_xlim(lo, top + 0.05 * (top - lo))
        _style(ax, title, metric)
    fig.text(0.01, 0.005, "Test split. Bars = mean over 5 seeds, whiskers = ±1 sd; orange dashed = Adamic-Adar.",
             fontsize=7, color=INK_2)
    fig.tight_layout(rect=(0, 0.02, 1, 1))
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def comparison_figure(s: pd.DataFrame, base: pd.DataFrame, path: Path) -> None:
    models = ["adamic_adar", "katz", "logreg", "lightgbm", "lightgbm_d2_specialist", "lightgbm_pair_focused"]
    agg = s.rename(columns={"mean": "value"})[["model", "split", "protocol", "subset", "metric", "value", "ci_low", "ci_high"]]
    b = base[base.model.isin(["adamic_adar", "katz"])][["model", "split", "protocol", "subset", "metric", "value", "ci_low", "ci_high"]]
    report.protocol_figure(pd.concat([b, agg]), "test", models, path,
                           note=" Learned models: mean over 5 seeds of the point estimate and of the CI bounds.",
                           protocols=("hard_active", "rank_hard_active", "hard", "rank_hard", "rank_random", "random"))
