def seed_summary(df: pd.DataFrame) -> pd.DataFrame:
    """mean ± sd of point estimates over seeds, plus the mean CI bounds."""
    g = df.groupby(["model", "split", "protocol", "subset", "metric"])
    return g.agg(mean=("value", "mean"), sd=("value", "std"), n_seeds=("seed", "nunique"),
                 ci_low=("ci_low", "mean"), ci_high=("ci_high", "mean")).reset_index()


def msd(x) -> str:
    return f"{x['mean']:.3f} ± {0 if pd.isna(x['sd']) else x['sd']:.3f}"


def table(s: pd.DataFrame, split, protocol, subset, metrics, models) -> pd.DataFrame:
    d = s[(s.split == split) & (s.protocol == protocol) & (s.subset == subset)]
    out = pd.DataFrame({"model": models})
    for m in metrics:
        x = d[d.metric == m].set_index("model")
        out[m] = [msd(x.loc[k]) if k in x.index else "" for k in models]
    return out


def heuristic_rows(base: pd.DataFrame, split, protocol, subset, metrics, models) -> pd.DataFrame:
    t = report.metric_table(base, protocol, subset, split, metrics, models)
    t["model"] = t["model"] + " (heuristic)"
    return t


def write_feature_report(cfg: dict, mix: dict, params: dict, val_best: dict, pf_params: dict | None = None) -> None:
    res, figs = Path(cfg["paths"]["results"]), Path(cfg["paths"]["figures"])
    fm = pd.read_csv(res / "feature_models.csv")
    base = pd.read_csv(res / "baselines.csv")
    paired = pd.read_csv(res / "feature_models_paired.csv")
    grid = pd.read_csv(res / "negative_mix_grid.csv")
    search = pd.read_csv(res / "lgbm_search.csv")
    abl = pd.read_csv(res / "ablation.csv")
    hl = pd.read_csv(res / "half_life_selection.csv")
    cov = pd.read_csv(Path(cfg["paths"]["report"]) / "features" / "coverage.csv")
    imp = pd.read_csv(Path(cfg["paths"]["report"]) / "features" / "importance.csv")
    s = seed_summary(fm)
    sa = seed_summary(abl)
    ks_r = [f"hits@{k}" for k in cfg["evaluation"]["rank_ks_random"]]
    pf_params = pf_params or {}
    refs = ["adamic_adar", "jaccard", "katz", "prefer_newer"]
    learned = [m for m in FINAL if m in set(fm.model)]

    seeded = set(fm.model)          # every model trained here (incl. the appendix shortcut model)

    def get(m, split, p, subset, metric):
        if m in seeded:
            d = s[(s.model == m) & (s.split == split) & (s.protocol == p) & (s.subset == subset) & (s.metric == metric)]
            return msd(d.iloc[0]) if len(d) else ""
        d = base[(base.model == m) & (base.split == split) & (base.protocol == p) & (base.subset == subset) & (base.metric == metric)]
        return report.fmt(*d[["value", "ci_low", "ci_high"]].iloc[0]) if len(d) else ""

    rows_order = learned + [f"{r}" for r in refs]
    out = ["# Feature-based models (logistic regression, LightGBM)", "",
           "_Generated by `scripts/run_feature_models.py` from `results/feature_models.csv`, "
           "`feature_models_paired.csv`, `negative_mix_grid.csv`, `lgbm_search.csv`, `ablation.csv`, "
           "`half_life_selection.csv`. Learned models: mean ± sd of the point estimate over 5 seeds "
           "(logistic regression is deterministic, so its sd is 0). Reference rows (Adamic-Adar, Jaccard, Katz, "
           "prefer_newer): point estimate [bootstrap 95% CI] from `results/baselines.csv`. Seed-mean confidence "
           "intervals and the multiplicity-corrected primary tests are in `results/final_comparison.md`._", "",
           "**How to read this.** Headline numbers are **macro within-group** scores: positives and negatives are "
           "compared inside the established and newcomer groups separately and averaged (audit M2). `hard_active` "
           "is the lead pair-level protocol; `hard` keeps negatives with inactive authors and therefore *includes "
           "activity*. Pooled numbers are kept but are affected by the newcomer imbalance. `prefer_newer` is a "
           "reference that only prefers pairs with a newer author. **`lightgbm_pair_focused` is the retrained "
           "model (distance-2 positives only, audit M1);** the pre-audit version is in the appendix as "
           "`lightgbm_pair_focused_shortcut`.", ""]

    out += ["## Choices made on validation", "",
            f"- Negative mix: logistic regression **hard fraction {mix['logreg'][0]:g}, 1:{mix['logreg'][1]}**; "
            f"LightGBM **hard fraction {mix['lightgbm'][0]:g}, 1:{mix['lightgbm'][1]}** (rule: best val pooled `hard` "
            "ROC-AUC among mixes with val rank_random MRR ≥ 90% of the best mix).",
            f"- LightGBM: num_leaves {params['num_leaves']}, learning_rate {params['learning_rate']:g}, "
            f"min_child_samples {params['min_child_samples']}, subsample {params['subsample']}, "
            f"colsample_bytree {params['colsample_bytree']}; early stopping on val hard AP."]
    for k, lab in (("lightgbm_pair_focused", "Pair-focused LightGBM (distance-2 positives vs 2023 activity-matched negatives)"),
                   ("lightgbm_pair_focused_shortcut", "Pair-focused LightGBM with the distance shortcut (appendix)")):
        if pf_params.get(k):
            q = pf_params[k]
            out.append(f"- {lab}: num_leaves {q['num_leaves']}, learning_rate {q['learning_rate']:g}, "
                       f"min_child_samples {q['min_child_samples']}; early stopping on val hard_active AP, "
                       "selected by val pooled hard_active ROC-AUC.")
    out += [f"- Recency half-life: {hl.sort_values('value', ascending=False)['model'].iloc[0].split('=')[1]} years "
            "(val hard ROC-AUC of recency-weighted Adamic-Adar alone).",
            "- Validation-best heuristic per protocol (paired-test reference, prefer_newer excluded): "
            + ", ".join(f"{p}: {h}" for p, h in val_best.items()) + "; Adamic-Adar is also tested on the pair-level protocols.",
            ""]
    out += ["## Embedding coverage (authors with ≥ 1 embedded work before the cutoff)", "",
            report.to_md(cov.assign(**{c: cov[c].map(lambda v: f"{v:.3f}") for c in cov.columns if c.startswith("share")})), ""]

    out += ["## Negative-mix grid (validation, seed 0, default LightGBM params)", "",
            "Pooled metrics, as used by the selection rule.", ""]
    rows = []
    for m, d in grid.groupby("model", sort=False):
        get_ = lambda p, mt=None, sub=None: d[(d.protocol == p) & (d.subset == (sub or report.POOLED[p][0]))
                                             & (d.metric == (mt or report.POOLED[p][1]))]["value"].iloc[0]
        rows.append({"model | mix": m, "hard_active ROC-AUC": f"{get_('hard_active'):.4f}",
                     "hard ROC-AUC": f"{get_('hard'):.4f}", "hard AP": f"{get_('hard', 'average_precision'):.4f}",
                     "rank_hard MRR": f"{get_('rank_hard'):.4f}", "rank_random MRR": f"{get_('rank_random'):.4f}",
                     "random ROC-AUC": f"{get_('random'):.4f}"})
    out += [report.to_md(pd.DataFrame(rows)), ""]
    out += ["## LightGBM searches (validation, chosen mix, seed 0)", ""]
    sp_ = search.pivot_table(index="model", columns="metric", values="value").reset_index()
    sp_ = sp_[["model", "roc_auc", "average_precision", "n_trees"]].sort_values("roc_auc", ascending=False)
    out += [report.to_md(sp_.round(4)), ""]

    for split in ("test", "val"):
        out += [f"## Final models — {split}", ""]
        out += report.pair_level_md(get, rows_order, split, cfg["evaluation"]["rank_ks_hard"])
        for p, sub, metrics in (("rank_random", "all", ks_r + ["mrr"]), ("random", "all", ["roc_auc", "average_precision"])):
            t = pd.DataFrame({"model": rows_order})
            for m_ in metrics:
                t[m_] = [get(m, split, p, sub, m_) for m in rows_order]
            out += [f"### {p} — {sub}", "", report.to_md(t), ""]

    out += ["## Paired bootstrap tests per seed (test) — secondary robustness column", "",
            "Difference = model − reference on identical test pairs/queries, on each protocol's headline metric "
            "(macro within-group for pair-level protocols). `sig. seeds` = seeds with p < 0.05 in the stated "
            "direction; the five tests share the test pairs, so k/5 is not k independent confirmations. Primary "
            "tests (one paired bootstrap on seed-averaged scores, Holm-corrected) are in `results/final_comparison.md`.", ""]
    pv = paired[paired.metric.str.endswith("_p_value")].rename(columns={"value": "p"})
    dv = paired[~paired.metric.str.endswith("_p_value")]
    m = dv.merge(pv[["model", "protocol", "subset", "seed", "p"]], on=["model", "protocol", "subset", "seed"])
    rows = []
    for (model, p), d in m.groupby(["model", "protocol"], sort=False):
        rows.append({"comparison": model, "protocol": p, "metric": f"{d['subset'].iloc[0]} {d['metric'].iloc[0]}",
                     "mean diff": f"{d['value'].mean():+.4f}",
                     "diff range (seeds)": f"[{d['value'].min():+.4f}, {d['value'].max():+.4f}]",
                     "sig. seeds (better)": f"{int(((d.p < 0.05) & (d.value > 0)).sum())}/{len(d)}",
                     "sig. seeds (worse)": f"{int(((d.p < 0.05) & (d.value < 0)).sum())}/{len(d)}",
                     "median p": f"{d['p'].median():.3f}"})
    out += [report.to_md(pd.DataFrame(rows)), ""]

    out += ["## Ablation by feature family (general LightGBM, chosen mix and params, test)", ""]
    ab = []
    for lab in ABL_ORDER:
        mname = f"lightgbm[{lab}]"
        row = {"features": lab}
        for p, sub, metric in (("hard_active", "macro", "roc_auc"), ("hard_active", "established_matched", "roc_auc"),
                               ("hard_active", "newcomer_matched", "roc_auc"), ("rank_hard_active", "macro", "query_auc"),
                               ("hard", "macro", "roc_auc"), ("hard_active", "all", "roc_auc")):
            d = sa[(sa.model == mname) & (sa.split == "test") & (sa.protocol == p) & (sa.subset == sub) & (sa.metric == metric)]
            row[f"{p} {sub} {metric}"] = msd(d.iloc[0]) if len(d) else ""
        ab.append(row)
    out += [report.to_md(pd.DataFrame(ab)), "", "![ablation](../figures/feature_models_ablation_test.png)", ""]

    out += ["## LightGBM gain importance by family (mean over seeds, general model)", "",
            "Measured on the training data (random negatives), so it overstates structure relative to its value on "
            "the pair-level protocols; the ablation is the evidence for which family matters.", ""]
    fi = imp[imp.model == "lightgbm"].groupby(["seed", "family"])["gain"].sum().groupby("family").mean()
    fi = (fi / fi.sum()).sort_values(ascending=False)
    out += [report.to_md(pd.DataFrame({"family": fi.index, "share of total gain": [f"{v:.3f}" for v in fi.values]})), ""]

    act_path = res / "activity_diagnostic.csv"
    if act_path.exists():
        act = pd.read_csv(act_path)
        actp = pd.read_csv(res / "activity_diagnostic_paired.csv")
        out += ["## Diagnostic: how much of the hard gain is author activity? (validation first)", "",
                "`neg_both_active` keeps only the saved hard negatives whose two authors both have a work in the "
                "prediction year (a subset of `neg_hard`; `hard_active` instead draws a fresh 1:1 sample from the full "
                "activity-matched pool, which is why the two gains differ, +0.042 vs +0.033 on test; audit m9). The "
                "subset uses label-window information to choose evaluation pairs only. **Validation is shown first: "
                "the decision to adopt `hard_active` rests on it** (audit M3); test is shown for completeness.", ""]
        for split in ("val", "test"):
            a = act[(act.split == split)]
            nn = a[(a.metric == "n_negatives") & (a.model == "adamic_adar")].set_index("subset")["value"]
            rows = []
            for mname, d in a[a.metric == "roc_auc"].groupby("model", sort=False):
                row = {"model": mname}
                for sub in ("all", "neg_both_active"):
                    x = d[d.subset == sub]["value"]
                    row[f"hard ROC-AUC, {sub} (n_neg={int(nn[sub]):,})"] = (
                        f"{x.mean():.3f} ± {x.std():.3f}" if len(x) > 1 else f"{x.mean():.3f}")
                pp = actp[(actp.split == split) & (actp.model == f"{mname} - adamic_adar")]
                for sub in ("all", "neg_both_active"):
                    dd = pp[(pp.subset == sub) & (pp.metric == "roc_auc_diff")]
                    pvv = pp[(pp.subset == sub) & (pp.metric == "roc_auc_diff_p_value")].set_index("seed")["value"]
                    if len(dd):
                        sig = int(sum((pvv.loc[s_] < 0.05) and (v > 0) for s_, v in zip(dd.seed, dd.value)))
                        worse = int(sum((pvv.loc[s_] < 0.05) and (v < 0) for s_, v in zip(dd.seed, dd.value)))
                        row[f"vs AA, {sub}"] = f"{dd.value.mean():+.3f} (better {sig}/5, worse {worse}/5)"
                rows.append(row)
            out += [f"### {split}", "", report.to_md(pd.DataFrame(rows).fillna("—")), ""]

    shortcut = [m for m in ("lightgbm_pair_focused_shortcut",) if m in set(fm.model)]
    out += ["## Appendix", ""]
    if shortcut:
        out += ["### Pair-focused LightGBM trained with the distance shortcut (pre-audit, superseded)", "",
                "> Trained on ALL train positives vs activity-matched negatives (all at distance 2): 40.5% of positives "
                "but 0% of negatives were at distance ≥ 3, so distance alone separated the classes in training and the "
                "model scored every distance-≥3 pair ≈ 0.995 (audit M1). Kept for the record.", ""]
        for split in ("test",):
            out += report.pair_level_md(get, shortcut + ["lightgbm_pair_focused"], split, cfg["evaluation"]["rank_ks_hard"],
                                        protocols=("hard_active", "rank_hard_active"))
            t = pd.DataFrame({"model": shortcut + ["lightgbm_pair_focused"]})
            for p_, sub, mt in (("random", "all", "roc_auc"), ("rank_random", "all", "mrr")):
                t[f"{p_} {mt}"] = [get(m, split, p_, sub, mt) for m in t["model"]]
            out += ["#### Easy protocols (shortcut model collapses; retrained model does not)", "", report.to_md(t), ""]
    out += report.positives_only_appendix(get, rows_order, "test")
    out += ["### diagnostic_all_vs_hard", "", report.DIAGNOSTIC_WARNING, "",
            report.to_md(table(s, "test", "diagnostic_all_vs_hard", "all", ["roc_auc", "average_precision"], learned)), ""]
    out += ["## Figures", "", "![models](../figures/feature_models_protocols_test.png)", ""]
    (res / "feature_models.md").write_text("\n".join(out))

    ablation_figure(sa, base, figs / "feature_models_ablation_test.png")
    comparison_figure(s, base, figs / "feature_models_protocols_test.png")


def _style(ax, title, xlabel):
    report._style(ax, title, xlabel)


def ablation_figure(sa: pd.DataFrame, base: pd.DataFrame, path: Path) -> None:
    panels = [("hard_active", "macro", "roc_auc", "hard_active macro ROC-AUC (lead)\nmean of within-group scores"),
              ("hard_active", "established_matched", "roc_auc", "hard_active ROC-AUC\nestablished group (matched)"),
              ("hard_active", "newcomer_matched", "roc_auc", "hard_active ROC-AUC\nnewcomer group (matched)"),
              ("rank_hard_active", "macro", "query_auc", "rank_hard_active macro query AUC\nmean of within-group scores"),
              ("hard", "macro", "roc_auc", "hard macro ROC-AUC\n(includes activity)"),
              ("hard_active", "all", "roc_auc", "hard_active pooled ROC-AUC\n(affected by newcomer imbalance)")]
    fig, axes = plt.subplots(2, 3, figsize=(12, 6.6), dpi=150)
    fig.patch.set_facecolor(SURFACE)
    y = np.arange(len(ABL_ORDER))[::-1]
    for ax, (p, sub, metric, title) in zip(axes.ravel(), panels):
        d = sa[(sa.split == "test") & (sa.protocol == p) & (sa.subset == sub) & (sa.metric == metric)]
        d = d.set_index("model").reindex([f"lightgbm[{a}]" for a in ABL_ORDER])
        ax.barh(y, d["mean"], color=SERIES[0], height=0.6)
        ax.errorbar(d["mean"], y, xerr=d["sd"].fillna(0), fmt="none", ecolor=INK, elinewidth=1, capsize=2)
        hi = float((d["mean"] + d["sd"].fillna(0)).max())
        b = base[(base.split == "test") & (base.protocol == p) & (base.subset == sub) & (base.metric == metric)
                 & (base.model == "adamic_adar")]
        ref = float(b["value"].iloc[0]) if len(b) else None
        lo = 0.4 if metric != "mrr" else 0.0
        top = max(hi, ref or 0) * 1.08
        for yi, v, sd in zip(y, d["mean"], d["sd"].fillna(0)):
            ax.text(v + sd + 0.01 * (top - lo), yi, f"{v:.3f}", va="center", fontsize=7.5, color=INK_2)
        if ref is not None:
            ax.axvline(ref, color=SERIES[1], linewidth=1.5, linestyle=(0, (3, 2)))
        ax.set_yticks(y)
        ax.set_yticklabels(ABL_ORDER)
        ax.set_xlim(lo, top + 0.05 * (top - lo))
        _style(ax, title, metric)
    fig.text(0.01, 0.005, "Test split. Bars = mean over 5 seeds, whiskers = ±1 sd; orange dashed = Adamic-Adar.",
             fontsize=7, color=INK_2)
    fig.tight_layout(rect=(0, 0.02, 1, 1))
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def comparison_figure(s: pd.DataFrame, base: pd.DataFrame, path: Path) -> None:
    models = ["prefer_newer", "adamic_adar", "jaccard", "logreg", "lightgbm", "lightgbm_d2_specialist", "lightgbm_pair_focused"]
    agg = s.rename(columns={"mean": "value"})[["model", "split", "protocol", "subset", "metric", "value", "ci_low", "ci_high"]]
    b = base[base.model.isin(["prefer_newer", "adamic_adar", "jaccard"])][["model", "split", "protocol", "subset", "metric", "value", "ci_low", "ci_high"]]
    report.protocol_figure(pd.concat([b, agg]), "test", models, path,
                           note="\nLearned models: mean of 5 seeds; whiskers = mean of per-seed CI endpoints "
                                "(seed-mean CIs: final_comparison.md).",
                           protocols=("hard_active", "rank_hard_active", "hard", "rank_hard", "rank_random", "random"))
